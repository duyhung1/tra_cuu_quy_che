"""Ports (blueprint §3). Services depend only on these protocols."""

from datetime import date
from typing import Protocol

from app.domain.types import Amendment, Answer, Document, Hit, PageText, ParsedDocument, Resolution, Unit, UsageRecord


class PdfExtractor(Protocol):
    def extract(self, data: bytes, max_pages: int) -> list[PageText]: ...


class DocumentStore(Protocol):
    revision: int

    def count(self) -> int: ...
    def exists(self, filename: str) -> bool: ...
    def add(self, filename: str, size: int, pages: int, parsed: ParsedDocument) -> int: ...
    def add_failed(self, filename: str, size: int, code: str) -> int: ...
    def list_documents(self) -> list[Document]: ...
    def ready_units(self) -> list[Unit]: ...
    def amendments(self) -> list[Amendment]: ...
    def documents_by_id(self) -> dict[int, Document]: ...


class UsageLog(Protocol):
    def record(self, rec: UsageRecord) -> None: ...


class Retriever(Protocol):
    def rebuild(self, units: list[Unit]) -> None: ...
    def search(self, question: str, k: int) -> list[Hit]: ...
    def score(self, question: str, unit: Unit) -> float: ...


class Answerer(Protocol):
    def answer(self, question: str, resolution: Resolution, docs: dict[int, Document],
               siblings: list[Unit] | None = None) -> Answer: ...


class Clock(Protocol):
    def today(self) -> date: ...
